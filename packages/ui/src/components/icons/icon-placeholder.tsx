type IconPlaceholderProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  lucide: keyof typeof solarIcons
  tabler?: string
  hugeicons?: string
  phosphor?: string
  remixicon?: string
  size?: number
}

export function IconPlaceholder({ lucide, ...props }: IconPlaceholderProps) {
  // The other libraries' names are dropped; only the lucide key is looked up.
  const svgProps: Record<string, unknown> = { ...props }
  for (const library of ["tabler", "hugeicons", "phosphor", "remixicon"]) {
    delete svgProps[library]
  }
  return <AppIcon icon={solarIcons[lucide]} {...svgProps} />
}
